@pytest.mark.asyncio
async def test_hf_call_tools_parsing():
    """Test the parsing of tool calls in the HuggingFace model call."""

    model = causalLM()

    mock_chunks = [
        "<tool_call>",
        '{"name": "web_search_tool",',
        '"arguments": {"query": "weather in NYC"}}',
        "</tool_call>"
    ]

    class MockStreamer:
        def __aiter__(self):
            self.chunks = iter(mock_chunks)
            return self

        async def __anext__(self):
            try:
                return next(self.chunks)
            except StopIteration:
                raise StopAsyncIteration

    with patch(
        "personal_assistant.models.causalLM.AsyncTextIteratorStreamer",
        return_value=MockStreamer()
    ), patch.object(model.model, "generate"):

        response = model._call_huggingface(
            [{"role": "user", "content": "Weather in NYC?"}],
            tools=[db_search_tool, web_search_tool]
        )

        responses = [chunk async for chunk in response]

    tool_responses = [
        chunk for chunk in responses
        if chunk.message.tool_calls
    ]

    assert len(tool_responses) == 1
    assert_valid_tool_call(tool_responses[0])


