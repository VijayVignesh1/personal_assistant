@pytest.mark.ollama
@pytest.mark.asyncio
async def test_ollama_tool_call():
    """Test the Ollama model call with tool invocation."""

    model = causalLM.__new__(causalLM)
    model.model = None
    model.ollama = "ollama"
    model.model_name = "test-model"

    expected_response = ollama.ChatResponse(
        model="test-model",
        created_at="2024-06-05T00:00:00Z",
        done=False,
        message=ollama.Message(
            role="assistant",
            content="",
            tool_calls=[
                {
                    "function": {
                        "name": "web_search_tool",
                        "arguments": {
                            "query": "weather in NYC"
                        }
                    }
                }
            ]
        )
    )

    async def mock_chat(*args, **kwargs):
        async def stream():
            yield expected_response

        return stream()

    with patch(
        "personal_assistant.models.causalLM.AsyncClient"
    ) as mock_client:

        mock_client.return_value.chat = AsyncMock(
            side_effect=mock_chat
        )

        response = model._call_ollama(
            [{"role": "user", "content": "Weather in NYC?"}],
            tools=[db_search_tool, web_search_tool]
        )

        responses = [chunk async for chunk in response]

    tool_responses = [
        chunk for chunk in responses
        if chunk.message.tool_calls
    ]

    assert len(tool_responses) == 1
    assert_valid_tool_call(tool_responses[0])